def test_what_the_task_keeps_reaches_the_contract(tmp_path) -> None:
    """The robot has no `controls.yaml`; the contract's block is what its
    controller reads the task's controls from, and what refuses a hook reading
    one the task does not keep. So the block carries them, as the file says.

    The control group is the unmutated dump, which loads with them -- so each
    failure above is its mutation's -- and posture, which keeps none.
    """
    import yaml

    import tasks

    path = tmp_path / "controls.yaml"
    path.write_text(yaml.safe_dump(_five_foot_doc()), "utf-8")
    kept = load_controls(path)
    assert set(kept.task) == {"claw_left", "claw_right", "arm_thumb_up", "arm_thumb_down", "arm_web_up",
                              "arm_to_face"}
    assert load_controls(POSTURE_SPEC).task == {}

    block = tasks.load_env_cfg("jumper.five_foot").controller_contract()
    assert block["task"] == {n: {"kind": t.kind, "does": t.does} for n, t in kept.task.items()}
    assert block["devices"]["gamepad"]["task"] == kept.pad_task
    assert block["devices"]["keyboard"]["task"] == {n: list(k) for n, k in kept.key_task.items()}


def test_a_key_written_twice_is_refused_rather_than_the_last_one_kept(tmp_path) -> None:
    """PyYAML keeps the last of two equal keys and says nothing.

    So an axis written twice in the keyboard's `axes` is one set of keys
    silently gone, and the completeness check cannot see it: the surviving line
    may be the one that was meant. Written as text, because a dict cannot hold
    the duplicate.
    """
    text = POSTURE_SPEC.read_text("utf-8")
    line = '      pitch:     { "+": [key_i], "-": [key_k] }\n'
    assert text.count(line) == 1
    path = tmp_path / "controls.yaml"
    path.write_text(text.replace(line, line + '      pitch:     { "+": [key_k], "-": [key_i] }\n'))
    with pytest.raises(ValueError, match="written twice"):
        load_controls(path)


def test_the_contract_carries_the_bands_and_the_ramp_the_command_was_trained_under() -> None:
    """A robot has no config to read a band or a rate from, so the block carries them.

    `jumper.five_foot`'s and `jumper.posture`'s pose commands narrow while the
    velocity command walks, and five_foot's ramps at 30 deg/s. The controller
    applies both from the contract (`deploy/fsm/src/operator.rs::CommandShaper`);
    a block that dropped them loads, drives, and hands a walking robot the
    standing band's lean -- a stick at full deflection it was never trained under.

    The control group is the velocity block, which has neither and must say so.
    """
    import tasks

    expected = {"jumper.five_foot": ("body_pose", True), "jumper.posture": ("posture", False)}
    for task, (term, ramps) in expected.items():
        cfg = tasks.load_env_cfg(task)
        blocks = {c["term"]: c for c in cfg.controller_contract()["command"]}
        live = cfg.commands[term]
        bands = blocks[term].get("bands")
        assert bands is not None, f"{task}: the {term} block carries no bands"
        assert bands["standing_below"] == pytest.approx(live.stand_threshold)
        assert bands["velocity_term"] == "twist"
        for axis, band in bands["moving"].items():
            value = getattr(live.moving, axis)
            low, high = (-value, value) if isinstance(value, float) else value
            assert band == pytest.approx([low, high]), f"{task}.{axis}"
        assert set(bands["moving"]) == {"twist", "pitch", "roll"}, task
        assert ("max_rate" in blocks[term]) is ramps, f"{task}: max_rate presence"
        if ramps:
            assert blocks[term]["max_rate"] == pytest.approx(live.max_rate)
        assert "bands" not in blocks["twist"] and "max_rate" not in blocks["twist"], task
