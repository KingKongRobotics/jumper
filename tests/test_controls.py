POSTURE_SPEC = Path(__file__).resolve().parents[1] / "tasks/jumper/posture/controls.yaml"


def test_the_contract_carries_numbers_a_robot_can_use() -> None:
    """The block `deploy/fsm` reads as `operator_controller/2`.

    Each rest as a **number**: the file names a config field (`neutral_height`),
    a robot has no config to look it up in, and a rest it could not resolve is
    a height of zero -- a body on the floor.

    Built the way export builds it, from the environment config the task
    returns, because the posture term is added after `velocity_env_cfg` and the
    block is attached as a callable for exactly that reason.
    """
    pytest.importorskip("mjlab", reason="the env config needs mjlab installed")
    import tasks
    from tasks.jumper.common.constants import STAND_Z

    cfg = tasks.load_env_cfg("jumper.posture")
    attached = cfg.controller_contract
    assert callable(attached), "the block must be built at export, after the posture term exists"
    block = attached()
    assert block["schema"] == "operator_controller/2"
    assert [c["term"] for c in block["command"]] == ["twist", "posture"]
    assert block["source"]["sha256"] == load_controls(POSTURE_SPEC).source_sha256
    height = next(a for a in block["command"][1]["axes"] if a["name"] == "height")
    assert height["rest"] == pytest.approx(STAND_Z) and height["rest_from"] == "neutral_height"
    # Moved, not placed: the robot integrates it from the number.
    # The file's own number, carried over: the value is the task's to tune.
    assert height["integrate_s"] == pytest.approx(load_controls(POSTURE_SPEC).integrating["height"])
    assert "integrate_s" not in next(a for a in block["command"][1]["axes"] if a["name"] == "pitch")

    # The control group: with no environment to read it from, the rest is
    # refused rather than written as a name or left out.
    with pytest.raises(ValueError, match="rests at `neutral_height`"):
        controller_contract(load_controls(POSTURE_SPEC), None)


def _posture_doc() -> dict:
    import yaml

    return yaml.safe_load(POSTURE_SPEC.read_text("utf-8"))


def _pad(d: dict) -> dict:
    return d["devices"]["gamepad"]


def _kb(d: dict) -> dict:
    return d["devices"]["keyboard"]


def _keys(d: dict) -> dict:
    return d["devices"]["keyboard"]["axes"]


def _axis(d: dict, name: str) -> dict:
    return next(a for c in d["command"] for a in c["axes"] if a["name"] == name)


