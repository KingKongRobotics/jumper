def test_every_reader_reads_the_one_dictionary() -> None:
    """One list, three readers, and no copies.

    It had a copy in each reader for a day: a Python table here, Rust consts in
    `deploy/fsm`, and a prose block in a deploy manifest. Adding a word meant
    remembering two other files, and forgetting one leaves a name that reads as
    supported and is refused on build -- or, worse, the other way round.

    So this checks the *wiring*, not the contents: that each reader resolves to
    `controller/vocabulary.json` and none of them carries a list of its own.
    """
    import re

    from controller import vocabulary
    from tasks.jumper.common.mdp.controls import _AXES, _BUTTONS

    root = Path(__file__).resolve().parents[1]
    assert vocabulary.PATH == root / "controller/vocabulary.json"

    # The task side holds no list; it is the dictionary's, verbatim.
    assert tuple(_AXES) == vocabulary.axes()
    assert _BUTTONS == frozenset(vocabulary.buttons())

    # The crate embeds the same file rather than restating it. `include_str!`
    # fixes the bytes at compile time, so a board carries no file and a browser
    # needs no fetch, and there is still one source.
    rs = (root / "deploy/fsm/src/vocabulary.rs").read_text("utf-8")
    assert 'include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/../../controller/vocabulary.json"))' \
        in rs.replace("\n", " ").replace("    ", ""), "the crate does not embed the dictionary"
    assert not re.search(r'const PAD_BUTTONS: \[&str', rs), "the crate kept a list of its own"

    # Control group: the parse is reading something, so the assertions above
    # cannot pass by comparing two empty things.
    assert len(vocabulary.buttons()) == 14 and len(vocabulary.axes()) == 6


def test_the_local_reader_reports_only_names_the_dictionary_knows() -> None:
    """`controller/` aligns a pad to the dictionary and stops there.

    Its job is not to decide what a button means -- that belongs to a task --
    so it must not have a spelling of its own either. `view` is the one name it
    reports that the dictionary does not accept, and the dictionary says why
    rather than leaving it looking like an oversight.
    """
    from controller import vocabulary
    from controller.xbox import BUTTONS

    reported = set(BUTTONS.values())
    accepted = set(vocabulary.buttons())
    assert reported - accepted == set(vocabulary.absent()), \
        "the reader reports a name the dictionary neither accepts nor explains"
    assert "view" in vocabulary.absent()


def test_x_and_y_are_recorded_as_unresolved() -> None:
    """A recorded disagreement, not a passing check.

    `controller/xbox.py` and the robot's pad service read evdev 307 and 308 the
    other way round from each other. One is wrong about which physical button it
    is, and only pressing it settles that. Nothing binds either today, so
    nothing is broken while it stands.

    This exists so the disagreement cannot be closed by somebody assuming. It
    fails when the note leaves the dictionary, which is the moment to say
    whether it was measured or guessed.
    """
    from controller import vocabulary
    from controller.xbox import BTN_NORTH, BTN_WEST

    assert (BTN_NORTH, BTN_WEST) == (307, 308)
    unresolved = {b["name"]: b.get("unresolved") for b in vocabulary.load()["buttons"]}
    assert unresolved["X"] and "307" in unresolved["X"], "the X/Y question left the dictionary"
    assert unresolved["Y"]
    # And it is visible to anyone who asks, not only to a reader of the JSON.
    assert "unresolved" in vocabulary.describe()



