"""The operator-control specification, and the code that is supposed to obey it.

Each task's `controls.yaml` exists because the signs used to live in the bodies
of the teleop modules, with the reasoning in their docstrings. A second program
-- the web simulator -- then had to re-derive them by reading those docstrings,
and got them right. Right by reading, not by agreement: a sign corrected here
would have left it driving the robot sideways with every other number still
correct, and nothing to notice.

Moving them into a file only helps if the code actually reads it, and that is
what these pin. The control group below is the check that `play`'s mapping is
reading the file rather than agreeing with it: flip a sign in the specification,
and the command must follow.

`jumper.posture`'s file is the full one -- two commands, a split stick, a shift
layer, an axis the controls move rather than place, a reset, and a keyboard with
a modifier -- so it is the base the malformed variants are made from; five_foot's
adds the controls a task keeps for itself. The four locomotion tasks carry the
plain case, generated by the `controls` skill's script.

Since 2026-09-29 the pad and the keyboard are two paths, each binding its own
inputs to what they do. So the keyboard has signs of its own now -- "+" is the
axis's positive as the file words it -- and the tests that drive it check them
against those words.
"""

from __future__ import annotations

import re
from dataclasses import replace
from pathlib import Path

import pytest

pytest.importorskip("yaml")

from tasks.jumper.common.mdp.controls import (  # noqa: E402
    controller_contract,
    load_controls,
)

#: Every locomotion task carries its own copy. They are meant to be identical;
#: `test_every_task_carries_the_same_controls` is what keeps them that way.
TASKS = ("flat", "tripod", "ripple", "tetrapod")
SPECS = {t: Path(__file__).resolve().parents[1] / "tasks/jumper" / t / "controls.yaml" for t in TASKS}
CONTROLS = load_controls(SPECS["tripod"])


def test_every_task_carries_the_same_controls() -> None:
    """Four copies, deliberately, and they have to stay one decision.

    The duplication is this repository's rule -- a parameter a task must own is
    written in each task, even where all four agree -- and the rule only works
    with something checking that the agreement is still there. Compared parsed,
    because the generated header names its own task; everything the file
    decides has to match. Diverging on purpose means changing this test and
    saying why.
    """
    import yaml

    decisions = {t: yaml.safe_load(SPECS[t].read_text("utf-8")) for t in TASKS}
    assert all(decisions.values()), "a locomotion task has an empty controls.yaml"
    first = decisions[TASKS[0]]
    diverged = [t for t, d in decisions.items() if d != first]
    assert not diverged, (
        f"the locomotion tasks' controls.yaml have diverged ({diverged}). They are "
        "each other's controls: a gait that needs different driving rules is a real "
        "difference and should be stated here rather than discovered."
    )


def test_the_file_says_which_way_the_robot_walks() -> None:
    """The three directions, stated rather than inferred from a device convention."""
    (twist,) = CONTROLS.commands
    assert [a.positive for a in twist.axes] == ["forward", "left", "counter-clockwise"]
    assert twist.frame == "body"
    assert twist.feeds == "velocity_commands"


@pytest.mark.parametrize("axis", ["lin_vel_x", "lin_vel_y", "ang_vel_z"])
def test_the_mapping_reads_the_file_rather_than_agreeing_with_it(axis: str) -> None:
    """The control group.

    Without this, every assertion about which way a stick drives passes against
    a mapping that ignores the specification entirely and has the three signs
    written into it -- which is the arrangement the file was introduced to end.
    Flip a sign in the specification and the command must follow.
    """
    from tasks.jumper.common.mdp.operator import deflections

    (b,) = CONTROLS.bindings[axis]
    values = dict.fromkeys(("Lx", "Ly", "Rx", "Ry", "LT", "RT"), 0.0)
    values[b.source] = 1.0
    before = deflections(values, False, CONTROLS)[axis]
    flipped = replace(CONTROLS, bindings={**CONTROLS.bindings, axis: (replace(b, sign=-b.sign),)})
    after = deflections(values, False, flipped)[axis]
    assert before == pytest.approx(-after)
    assert before != 0.0


def test_the_keyboard_names_what_each_key_does() -> None:
    """Keystrokes are bound to directions of the file's axes by the
    dictionary's names: W is forward, and every axis is reached both ways."""
    assert "key_w" in CONTROLS.key_axes["lin_vel_x"].plus, "W is towards forward, the axis's +"
    assert "key_s" in CONTROLS.key_axes["lin_vel_x"].minus
    for axis, keys in CONTROLS.key_axes.items():
        assert keys.unbound is None and keys.plus and keys.minus, axis
    assert CONTROLS.key_release == ("key_escape",)


def test_the_locomotion_keyboard_reaches_both_ends_of_every_axis() -> None:
    """The keyboard alone drives each velocity axis to the edge of its range,
    through the operator `play` uses: each "+" keystroke to the axis's top and
    each "-" one to its bottom. A keyboard whose words and signs disagreed
    would walk the robot backwards on W, with every screen plausible."""
    pytest.importorskip("mjlab", reason="the env config needs mjlab installed")
    import tasks
    from tasks.jumper.common.mdp.operator import Operator, spans

    cfg = tasks.load_env_cfg("jumper.tripod", play=True)
    edges = spans(CONTROLS.command("twist"), cfg.commands["twist"])
    names = [a.name for a in CONTROLS.command("twist").axes]
    for i, axis in enumerate(names):
        for strokes, end in [(CONTROLS.key_axes[axis].plus, 1), (CONTROLS.key_axes[axis].minus, 0)]:
            for stroke in strokes:
                clock = _Clock()
                op = Operator(CONTROLS, listen=False, clock=clock)
                op.attach("twist", edges)
                assert op.key(stroke, True), stroke
                clock.t = CONTROLS.full_after_s
                assert op.command("twist")[i] == pytest.approx(edges[axis][end]), stroke


def test_a_modifier_with_nothing_to_do_does_not_take_over(tmp_path) -> None:
    """A modifier that is a chord's and nothing on its own -- Shift, with the
    twist put on Shift + J / L as jumper.posture had it until 2026-09-29 --
    pressed alone leaves the command with the sampler, as the controller
    does, which only takes over for a keystroke that acts. J pressed with it is
    the twist, and takes over: the control group."""
    pytest.importorskip("mjlab", reason="the env config needs mjlab installed")
    import tasks
    import yaml
    from tasks.jumper.common.mdp.operator import Operator, spans

    doc = _posture_doc()
    _keys(doc)["twist"] = {"+": ["shift+key_j"], "-": ["shift+key_l"]}
    spec = tmp_path / "controls.yaml"
    spec.write_text(yaml.safe_dump(doc), "utf-8")
    controls = load_controls(spec)
    cfg = tasks.load_env_cfg("jumper.posture", play=True)
    op = Operator(controls, listen=False, clock=_Clock())
    for term in ("twist", "posture"):
        op.attach(term, spans(controls.command(term), cfg.commands[term]))
    assert op.key("key_left_shift", True), "Shift is a key the file reads"
    assert op.command("twist") is None, "Shift alone took the command from the sampler"
    op.key("key_j", True)
    assert op.command("twist") is not None, "Shift + J did not take over"
    assert not op.key("keypad_5", True), "a key the file does not read reports as such"


class _Clock:
    """Seconds, moved by the test: what a key's hold is measured by."""

    def __init__(self) -> None:
        self.t = 0.0

    def __call__(self) -> float:
        return self.t


